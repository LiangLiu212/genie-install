#!/usr/bin/env bash
# setup_deps.sh -- resolve GENIE's dependencies from the DUNE CVMFS Spack instance, build the one
# package it lacks (Boost with the timer library, which INCL++ and GENIE's INCL interface link)
# into ./spack-packages, and write ./spack-env.sh: the environment file that setup_genie_incl.sh
# sources on every login. This is the only script that runs spack. Run it once, from anywhere:
#   bash scripts/setup_deps.sh
#
# Knobs (environment variables, all optional):
#   GI_DUNE_SPACK     Spack instance           default /cvmfs/dune.opensciencegrid.org/spack/v1.2.2
#   GI_SPACK_PYTHON   python that runs spack   default /usr/bin/python3: the instance's bootstrapped
#                                              clingo (concretizer) is built for the system python 3.9
#   GI_DEPS_FILE      pinned dependency list   default spack-config/deps.txt
#   GI_BOOST_SPEC     the local Boost build    default below (1.82.0 like CVMFS, + timer, gcc 12.5)
#   GI_NJOBS          parallel build jobs      default: the cgroup CPU quota, else nproc
#
# Layout after a successful run:
#   spack-config/config.yaml   generated scope: install tree, stage and caches under this directory
#   spack-packages/            the local Boost (and its gcc-runtime copy), chained to the CVMFS trees
#   spack-env.sh               `spack load --sh` of the pinned packages + the Boost, rewritten so that
#                              PATH-like variables are prepended, plus GI_PREFIX_<name> for each package
set -euo pipefail
log() { printf '\n=== %s  [%s]\n' "$*" "$(date '+%F %T')"; }
die() { printf 'setup_deps.sh: ERROR: %s\n' "$*" >&2; exit 1; }

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DUNE_SPACK="${GI_DUNE_SPACK:-/cvmfs/dune.opensciencegrid.org/spack/v1.2.2}"
DEPS_FILE="${GI_DEPS_FILE:-$ROOT_DIR/spack-config/deps.txt}"
BOOST_SPEC="${GI_BOOST_SPEC:-boost@1.82.0 +timer +chrono +system +date_time +program_options cxxstd=17 target=x86_64_v3 %c,cxx=gcc@12.5.0}"
CONFIG_SCOPE="$ROOT_DIR/spack-config"
ENV_FILE="$ROOT_DIR/spack-env.sh"
T0=$(date +%s)

# `nproc` honours OMP_NUM_THREADS (1 on the Fermilab EAF); the cgroup CPU quota is the truth.
default_jobs() {
  local q p
  if read -r q p < /sys/fs/cgroup/cpu.max 2>/dev/null && [[ "$q" != max ]]; then
    echo $(( (q + p - 1) / p ))
  else
    env -u OMP_NUM_THREADS nproc
  fi
}
NJOBS="${GI_NJOBS:-$(default_jobs)}"
libdir() { if ls "$1"/lib64/*.so* >/dev/null 2>&1; then echo "$1/lib64"; else echo "$1/lib"; fi; }

log "spack instance $DUNE_SPACK"
[[ -f "$DUNE_SPACK/share/spack/setup-env.sh" ]] || die "no Spack at $DUNE_SPACK (is /cvmfs/dune.opensciencegrid.org mounted?)"
export SPACK_PYTHON="${GI_SPACK_PYTHON:-/usr/bin/python3}"
[[ -x "$SPACK_PYTHON" ]] || die "SPACK_PYTHON=$SPACK_PYTHON is not executable"
# shellcheck disable=SC1091
source "$DUNE_SPACK/share/spack/setup-env.sh"
command -v spack >/dev/null || die "spack is not on PATH after sourcing $DUNE_SPACK/share/spack/setup-env.sh"
# Local configuration scope (-C): a writable install tree, stage and caches next to this file;
# upstreams.yaml (committed) chains the read-only CVMFS trees. Absolute paths, hence generated.
cat > "$CONFIG_SCOPE/config.yaml" <<EOC
# generated by scripts/setup_deps.sh on $(date '+%F %T') -- do not edit, do not commit
config:
  install_tree:
    root: $ROOT_DIR/spack-packages
  build_stage:
    - $ROOT_DIR/spack-stage/build
  source_cache: $ROOT_DIR/spack-stage/source-cache
  misc_cache: $ROOT_DIR/spack-stage/misc-cache
EOC
# every spack call: our scope, and without the instance's harmless read-only/deprecation warnings
sp() { spack -C "$CONFIG_SCOPE" "$@" 2> >(grep -v -E 'Warning: (Spack is trying attach|Ignoring write error on readonly)' >&2 || true); }
printf 'spack   %s\npython  %s\njobs    %s\nscope   %s\n' "$(sp --version)" "$SPACK_PYTHON" "$NJOBS" "$CONFIG_SCOPE"

log "pinned dependencies ($DEPS_FILE)"
NAMES=(); SPECS=(); FLAGS=()
while read -r name spec flag _; do
  [[ -z "$name" || "$name" == \#* ]] && continue
  NAMES+=("$name"); SPECS+=("$spec"); FLAGS+=("${flag:-load}")
done < "$DEPS_FILE"
[[ ${#NAMES[@]} -gt 0 ]] || die "no entries in $DEPS_FILE"
HASHES=(); for s in "${SPECS[@]}"; do HASHES+=("/${s##*/}"); done
found=$(sp find -p --no-groups "${HASHES[@]}") || die "a pinned package is missing from $DUNE_SPACK: spack find -p ${HASHES[*]}"
declare -A PREFIX
while read -r pkg prefix; do
  [[ -z "$pkg" || "$pkg" == '==>' || "$pkg" == --* ]] && continue
  PREFIX["${pkg%%@*}"]="$prefix"
done <<< "$found"
for i in "${!NAMES[@]}"; do
  n=${NAMES[$i]}
  [[ -n "${PREFIX[$n]:-}" && -d "${PREFIX[$n]}" ]] || die "no install prefix for $n (${SPECS[$i]})"
  printf '%-12s %-28s %s%s\n' "$n" "${SPECS[$i]}" "${PREFIX[$n]}" "$([[ ${FLAGS[$i]} == external ]] && echo '  (external, not loaded)')"
done

log "Boost with the timer library (every CVMFS Boost is built without it)"
boost_hash() { sp find -l --no-groups 'boost +timer +date_time +program_options +system' 2>/dev/null | awk '!/^(==>|--)/ && NF {print $1; exit}'; }
h=$(boost_hash || true)
if [[ -z "$h" ]]; then
  printf 'spec: %s\n' "$BOOST_SPEC"
  sp install -j "$NJOBS" --fail-fast "$BOOST_SPEC" || die "spack install of the Boost failed"
  h=$(boost_hash || true); [[ -n "$h" ]] || die "Boost not found after the install"
fi
PREFIX[boost]=$(sp find -p --no-groups "/$h" | awk '!/^(==>|--)/ && NF {print $2; exit}')
[[ -f "${PREFIX[boost]}/lib/libboost_timer.so" ]] || die "${PREFIX[boost]}/lib/libboost_timer.so missing"
printf '%-12s %-28s %s\n' boost "boost@1.82.0/$h" "${PREFIX[boost]}"

log "write $ENV_FILE"
LOAD=(); for i in "${!NAMES[@]}"; do [[ ${FLAGS[$i]} == external ]] || LOAD+=("${HASHES[$i]}"); done
LOAD+=("/$h")
# `spack load --sh` prints absolute values that embed the caller's PATH etc. Run it in a minimal
# environment, record the variables before the load, and rewrite each list variable X that came
# out as "<new>:<before>" (or as a fresh value) into  export X="<new>${X:+:$X}"  so the file can be
# sourced in any shell and prepends instead of replacing.
raw=$(env -i HOME="$HOME" USER="${USER:-$(id -un)}" TMPDIR="${TMPDIR:-/tmp}" PATH=/usr/bin:/bin SPACK_PYTHON="$SPACK_PYTHON" \
      bash -c 'source "$1/share/spack/setup-env.sh" >/dev/null 2>&1 || exit 9; env; echo "__GI_LOAD__"; spack -C "$2" load --sh "${@:3}" 2>/dev/null' \
      _ "$DUNE_SPACK" "$CONFIG_SCOPE" "${LOAD[@]}") || die "spack load --sh failed"
pre=${raw%%$'\n'__GI_LOAD__$'\n'*}; post=${raw#*$'\n'__GI_LOAD__$'\n'}
[[ "$post" == *"export "* ]] || die "spack load --sh printed nothing"
declare -A BEFORE
while IFS='=' read -r k v; do [[ -n "$k" ]] && BEFORE[$k]=$v; done <<< "$pre"
is_list() { case "$1" in PATH|LD_LIBRARY_PATH|LIBRARY_PATH|CMAKE_PREFIX_PATH|PKG_CONFIG_PATH|MANPATH|PYTHONPATH|ACLOCAL_PATH|C_INCLUDE_PATH|CPLUS_INCLUDE_PATH|ROOT_LIBRARY_PATH|ROOT_INCLUDE_PATH|MODULEPATH|XDG_DATA_DIRS) return 0;; *) return 1;; esac; }
{
  printf '# spack-env.sh -- generated by scripts/setup_deps.sh on %s (%s); do not edit, do not commit.\n' "$(date '+%F %T')" "$(hostname)"
  printf '# `spack load --sh %s`\n# from %s plus the local Boost, with list variables rewritten to prepend.\n' "${LOAD[*]}" "$DUNE_SPACK"
  printf '# Sourced by ../setup_genie_incl.sh; the GI_PREFIX_* variables feed scripts/build_*.sh.\n'
  printf 'export GI_ENV_FILE="%s"\nexport GI_DUNE_SPACK="%s"\nexport GI_SPACK_PYTHON="%s"\n' "$ENV_FILE" "$DUNE_SPACK" "$SPACK_PYTHON"
  for n in "${NAMES[@]}" boost; do printf 'export GI_PREFIX_%s="%s"\n' "$(printf '%s' "$n" | tr 'a-z-' 'A-Z_')" "${PREFIX[$n]}"; done
  printf '# --- spack load --sh ---\n'
  while IFS= read -r line; do
    line=${line%;}; line=${line#"${line%%[![:space:]]*}"}
    [[ -z "$line" ]] && continue
    if [[ "$line" == export\ *=* ]]; then
      kv=${line#export }; var=${kv%%=*}; val=${kv#*=}
      val=${val#\"}; val=${val%\"}
      b=${BEFORE[$var]:-}
      if [[ -n "$b" && "$val" == "$b" ]]; then continue; fi
      if [[ -n "$b" && "$val" == *":$b" ]]; then val=${val%:"$b"}; fi
      if is_list "$var"; then
        val=$(printf '%s' "$val" | tr ':' '\n' | awk 'NF && !seen[$0]++' | paste -sd:)   # spack lists each dir twice
        printf 'export %s="%s${%s:+:$%s}"\n' "$var" "$val" "$var" "$var"
      else printf 'export %s="%s"\n' "$var" "$val"; fi
    else
      printf '%s\n' "$line"
    fi
  done < <(printf '%s\n' "$post" | tr ';' '\n')
  printf '# --- end of spack load --sh ---\n'
  if ! grep -q 'export CC=' <<< "$post"; then
    printf '# the compilers the dependencies were built with\nexport CC="%s/bin/gcc" CXX="%s/bin/g++" FC="%s/bin/gfortran"\n' "${PREFIX[gcc]}" "${PREFIX[gcc]}" "${PREFIX[gcc]}"
  fi
  # `spack load` puts a package's lib directory on LD_LIBRARY_PATH only when the package asks for it
  # (spack binaries use rpath). GENIE and INCL++ link without rpath, so their loader needs every
  # dependency's lib directory, and gcc 12.5's runtime (its libstdc++.so.6 is newer than the system one).
  libs=""
  for n in boost pythia8 lhapdf log4cpp gsl; do d=$(libdir "${PREFIX[$n]}"); [[ -d "$d" ]] && libs="$libs$d:"; done
  rootlib=$("${PREFIX[root]}/bin/root-config" --libdir); [[ -d "$rootlib" ]] && libs="$libs$rootlib:"
  libs="$libs${PREFIX[gcc-runtime]}/lib"
  printf '# library directories of Boost, Pythia8, LHAPDF, log4cpp, GSL, ROOT and the gcc 12.5 runtime: GENIE and\n# INCL++ are linked without rpath, and spack load lists only the directories packages ask for (TBB)\n'
  printf 'export LD_LIBRARY_PATH="%s${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"\n' "$libs"
} > "$ENV_FILE"

log "checks (in a fresh shell that sources $ENV_FILE)"
bash -c "
  set -e; source '$ENV_FILE'
  for t in g++ gfortran cmake root-config gsl-config lhapdf-config log4cpp-config; do printf '%-14s %s\n' \"\$t\" \"\$(command -v \$t)\"; done
  case \"\$(command -v g++)\" in '$(printf '%s' "${PREFIX[gcc]}")'/*) ;; *) echo 'g++ is not the spack gcc 12.5'; exit 1;; esac
  printf 'g++ %s | cmake %s | ROOT %s (%s) | gsl %s | LHAPDF %s | log4cpp %s\n' \"\$(g++ -dumpfullversion)\" \"\$(cmake --version | head -1 | awk '{print \$3}')\" \"\$(root-config --version)\" \"\$(root-config --cflags | grep -o 'std=c++[0-9]*')\" \"\$(gsl-config --version)\" \"\$(lhapdf-config --version)\" \"\$(log4cpp-config --version)\"
  [[ \"\$(root-config --has-mathmore)\" == yes ]] || { echo 'ROOT without MathMore'; exit 1; }
  printf '%s\n' \"\$LD_LIBRARY_PATH\" | tr ':' '\n' | grep -q gcc-runtime || { echo 'gcc-runtime missing from LD_LIBRARY_PATH'; exit 1; }
  echo 'int main(){return 0;}' > /tmp/gi_\$\$.cc && g++ -std=c++17 /tmp/gi_\$\$.cc -o /tmp/gi_\$\$ && /tmp/gi_\$\$ && rm -f /tmp/gi_\$\$ /tmp/gi_\$\$.cc && echo 'compile+run test program: ok'
" || die "environment check failed"
printf 'lines in %s: %s\n' "$ENV_FILE" "$(wc -l < "$ENV_FILE")"
log "SETUP_DEPS_OK in $(( ($(date +%s) - T0) / 60 )) min -- next: source $ROOT_DIR/setup_genie_incl.sh"
